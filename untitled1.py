"""### Upload and read the .numbers file
If the file is already uploaded to the root directory `/clssssssssss.numbers`, we will read its first sheet and convert it to a pandas DataFrame.
"""

import os
import pandas as pd
from numbers_parser import Document

file_path = '/clssssssssss.numbers'

if os.path.exists(file_path):
    doc = Document(file_path)
    sheets = doc.sheets
    tables = sheets[0].tables
    data = tables[0].rows(as_list=True)

    # Convert to DataFrame
    df = pd.DataFrame(data[1:], columns=data[0])
    display(df.head())
else:
    print(f"File not found at {file_path}. Please upload it using the file explorer on the left.")

"""### Exploratory Data Analysis (EDA)
We will analyze the structure of the dataset, check for missing values, view summary statistics, and prepare visualizations.
"""

import matplotlib.pyplot as plt
import seaborn as sns

# Basic dataset info
if 'df' in globals():
    print("--- Dataset Shape ---")
    print(df.shape)
    print("\n--- Info ---")
    print(df.info())
    print("\n--- Missing Values ---")
    print(df.isnull().sum())
    print("\n--- Descriptive Statistics ---")
    display(df.describe(include='all'))
else:
    print("Please run the previous cells first to load the 'df' DataFrame.")

"""### Visualizing Column Distributions and Relations
Let's plot the distribution of numeric variables or count plots for categorical variables to better understand our dataset.
"""

if 'df' in globals() and not df.empty:
    # Select numeric columns for distribution plotting
    numeric_cols = df.select_dtypes(include=['number']).columns.tolist()
    if numeric_cols:
        print(f"Found numeric columns: {numeric_cols}")
        for col in numeric_cols[:3]:  # Plot up to first 3 numeric columns
            plt.figure(figsize=(8, 4))
            sns.histplot(df[col].dropna(), kde=True, color='skyblue')
            plt.title(f'Distribution of {col}')
            plt.grid(True, linestyle='--', alpha=0.5)
            plt.show()
    else:
        # If no numeric columns detected, plot value counts of the first few columns
        print("No numeric columns found. Plotting categorical distributions instead.")
        for col in df.columns[:3]:
            plt.figure(figsize=(10, 4))
            sns.countplot(data=df, x=col, order=df[col].value_counts().index[:10], palette='viridis')
            plt.title(f'Top 10 categories in {col}')
            plt.xticks(rotation=45, ha='right')
            plt.grid(True, axis='y', linestyle='--', alpha=0.5)
            plt.show()
else:
    print("DataFrame 'df' is not available or empty.")

"""### Custom Matplotlib (Manplot) Visualizations
We will manually configure matplotlib properties (figure, axes, titles, grid, colors, and layout) to generate highly customized plots of the loaded dataset.
"""

if 'df' in globals() and not df.empty:
    # Manually configure a plot for the first column
    target_col = df.columns[0]
    value_counts = df[target_col].value_counts().head(10)

    # Manual matplotlib adjustments
    fig, ax = plt.subplots(figsize=(10, 6))
    colors = ['#1f77b4', '#ff7f0e', '#2ca02c', '#d62728', '#9467bd']

    ax.bar(value_counts.index.astype(str), value_counts.values, color=colors[:len(value_counts)], edgecolor='black', linewidth=1.2)

    # Set title and labels manually with custom font sizes
    ax.set_title(f'Distribution of {target_col} (Top 10)', fontsize=16, fontweight='bold', pad=15)
    ax.set_xlabel(target_col, fontsize=12, labelpad=10)
    ax.set_ylabel('Count', fontsize=12, labelpad=10)

    # Handle tick rotation and alignment manually
    ax.set_xticklabels(value_counts.index.astype(str), rotation=45, ha='right', fontsize=10)

    # Enable a clean grid manually
    ax.grid(True, which='both', linestyle='--', linewidth=0.5, alpha=0.7)
    ax.set_axisbelow(True)

    # Adjust layout to prevent clipping
    plt.tight_layout()
    plt.show()
else:
    print("DataFrame 'df' is empty or not loaded. Please run the setup and loading cells first.")